def literal(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

lines = []
for row in ROWS:
    assert len(row) == 13, (row[0], len(row))
    cells = ", ".join(literal(c) for c in row)
    lines.append("            new[] { " + cells + " },")

block = "\n".join(lines)
# 插进 kExtraDescriptions 的结尾（最后一个 `};` 之前）
i = src.index("private static readonly string[][] kExtraDescriptions")
j = src.index("        };", src.index("RetraceNowBinding.desc", i))
src = src[:j] + block + "\n" + src[j:]
io.open(SRC, "w", encoding="utf-8").write(src)
print("追加", len(ROWS), "行说明")
